// Generates src/styles/icons.css: Lucide glyphs as data-URI CSS masks keyed by
// `[data-icon]`, plus the fold-marker chevron. Run by hand (`pnpm generate:icons`)
// and commit the output. The icon list comes from the plugin's own source and
// the Lucide version is pinned in package.json (lucide-static).
import { readFileSync, writeFileSync } from "node:fs";
import { CALLOUT_TYPES } from "../src/callouts.ts";

const lucide = new URL("../node_modules/lucide-static/", import.meta.url);
const version = JSON.parse(
  readFileSync(new URL("package.json", lucide), "utf8"),
).version;

function dataUri(name) {
  const svg = readFileSync(new URL(`icons/${name}.svg`, lucide), "utf8")
    .replace(/<!--[\s\S]*?-->/g, "")
    .replace(/\s+class="[^"]*"/, "")
    .replace(/\s+/g, " ")
    .replace(/> </g, "><")
    .replace(/ \/>/g, "/>")
    .replace(/" >/g, '">')
    .trim();
  return `url("data:image/svg+xml,${encodeURIComponent(svg).replace(/%20/g, " ").replace(/%3D/g, "=").replace(/%2F/g, "/").replace(/%3A/g, ":").replace(/%22/g, "'")}")`;
}

const icons = [...new Set(Object.values(CALLOUT_TYPES).map((t) => t.icon))];
const mask = (v) =>
  `  -webkit-mask: ${v} center / contain no-repeat;\n  mask: ${v} center / contain no-repeat;`;

let css = `/*
 * GENERATED by scripts/generate-icons.mjs from lucide-static ${version} (ISC,
 * see LICENSE-LUCIDE). Do not edit; run \`pnpm generate:icons\`.
 *
 * Icons are masks painted with the Callout color. \`--callout-icon\` is the
 * override hook: set it (a \`url(...)\` mask) to give a custom Callout Type an
 * icon. Unknown \`data-icon\` names set nothing, so no icon is drawn.
 */

:where(.markdown-rendered) .callout-title-icon {
  background-color: rgb(var(--callout-color));
  -webkit-mask-image: var(--callout-icon, linear-gradient(transparent, transparent));
  mask-image: var(--callout-icon, linear-gradient(transparent, transparent));
  -webkit-mask-position: center;
  mask-position: center;
  -webkit-mask-repeat: no-repeat;
  mask-repeat: no-repeat;
  -webkit-mask-size: contain;
  mask-size: contain;
}
`;
for (const name of icons) {
  css += `\n:where(.markdown-rendered) .callout-title-icon[data-icon="${name}"] {\n  --callout-icon: ${dataUri(name)};\n}\n`;
}
css += `
/* Fold marker: a Lucide chevron-down, rotated by CSS when the Callout is closed. */
:where(.markdown-rendered) .callout.is-collapsible > .callout-title::after {
  content: "";
  flex: none;
  width: 1.25em;
  height: 1.25em;
  margin-left: auto;
  background-color: currentColor;
${mask(dataUri("chevron-down"))}
  transition: transform 0.15s;
}
`;
writeFileSync(new URL("../src/styles/icons.css", import.meta.url), css);
